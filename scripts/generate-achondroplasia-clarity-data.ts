/**
 * Generates src/data/achondroplasia-clarity-data.ts from the original supplementary CSV
 * (Hoover-Fong et al. 2021, Additional file 2 / Table S1, 13023_2021_2141_MOESM2_ESM.csv).
 *
 * Run: npx tsx scripts/generate-achondroplasia-clarity-data.ts <path-to-csv> <retrieval-date YYYY-MM-DD>
 *
 * Only these columns are used: sex, age (months), ht mean, htsd, wt_mean, wt sd lower, wt sd upper.
 * Numbers are copied as the CSV text (no re-rounding, no unit change, no manual correction).
 * Rows are kept for completed months 0 through 216 (18.0 years); later rows are not needed.
 * The script fails instead of writing the file when a used column is missing, a value is empty or
 * non-finite, a standard deviation is not positive, or a month is duplicated, out of order or missing.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE_URL = 'https://media.springernature.com/original/springer-static/esm/art%3A10.1186%2Fs13023-021-02141-4/MediaObjects/13023_2021_2141_MOESM2_ESM.csv';
const MAX_MONTH = 216;
const OUT = new URL('../src/data/achondroplasia-clarity-data.ts', import.meta.url);

const [csvPath, retrievalDate] = process.argv.slice(2);
if (!csvPath || !/^\d{4}-\d{2}-\d{2}$/.test(retrievalDate ?? '')) {
  throw new Error('usage: generate-achondroplasia-clarity-data.ts <csv> <YYYY-MM-DD>');
}

const bytes = readFileSync(csvPath);
const sha256 = createHash('sha256').update(bytes).digest('hex');
const text = bytes.toString('utf8');

function parseCsv(t: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (quoted) {
      if (c === '"') {
        if (t[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && t[i + 1] === '\n') i++;
      row.push(field); field = ''; rows.push(row); row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const rows = parseCsv(text);
const header = rows[0].map(h => h.trim());
const col = (name: string): number => {
  const matches = header.flatMap((h, i) => (h === name ? [i] : []));
  if (matches.length !== 1) throw new Error(`column "${name}" found ${matches.length} times`);
  return matches[0];
};
const C = {
  sex: col('Sex (M=0, F = 1)'),
  month: col('age (months)'),
  htMean: col('ht mean'),
  htSd: col('htsd'),
  wtMean: col('wt_mean'),
  wtSdLower: col('wt sd lower'),
  wtSdUpper: col('wt sd upper'),
};

const lines: Record<'0' | '1', string[]> = { '0': [], '1': [] };
const lastMonth: Record<string, number> = { '0': -1, '1': -1 };
for (const r of rows.slice(1)) {
  const sex = r[C.sex].trim();
  if (sex !== '0' && sex !== '1') throw new Error(`unexpected sex code "${sex}"`);
  const month = Number(r[C.month]);
  if (!Number.isInteger(month)) throw new Error(`bad month "${r[C.month]}"`);
  if (month <= lastMonth[sex]) throw new Error(`months not strictly ascending for sex ${sex} at ${month}`);
  if (month > lastMonth[sex] + 1) throw new Error(`gap before month ${month} for sex ${sex}`);
  lastMonth[sex] = month;
  if (month > MAX_MONTH) continue;
  const texts = [C.htMean, C.htSd, C.wtMean, C.wtSdLower, C.wtSdUpper].map(i => r[i].trim());
  texts.forEach((t, k) => {
    if (t === '' || !Number.isFinite(Number(t))) throw new Error(`bad value "${t}" at sex ${sex} month ${month} (${k})`);
  });
  if (!(Number(texts[1]) > 0) || !(Number(texts[3]) > 0) || !(Number(texts[4]) > 0)) {
    throw new Error(`non-positive SD at sex ${sex} month ${month}`);
  }
  lines[sex].push(`  [${month}, ${texts.join(', ')}],`);
}
for (const sex of ['0', '1'] as const) {
  if (lines[sex].length !== MAX_MONTH + 1) throw new Error(`sex ${sex}: expected ${MAX_MONTH + 1} rows, got ${lines[sex].length}`);
}

const out = `/**
 * Achondroplasia growth reference (CLARITY, US cohort): mean and standard deviation by completed month.
 *
 * GENERATED by scripts/generate-achondroplasia-clarity-data.ts. Do not edit by hand or re-round.
 *
 * Source: Hoover-Fong JE, Schulze KJ, Alade AY, et al. Growth in achondroplasia including stature, weight,
 *   weight-for-height and head circumference from CLARITY: achondroplasia natural history study - a
 *   multi-center retrospective cohort study of achondroplasia in the US.
 *   Orphanet J Rare Dis. 2021;16:522. DOI: 10.1186/s13023-021-02141-4 (CC BY 4.0).
 * File:   Additional file 2 (Table S1), 13023_2021_2141_MOESM2_ESM.csv
 * URL:    ${SOURCE_URL}
 * Retrieved: ${retrievalDate}
 * SHA-256 of the original file: ${sha256}
 *
 * Columns used from the CSV: "Sex (M=0, F = 1)", "age (months)", "ht mean", "htsd", "wt_mean",
 * "wt sd lower", "wt sd upper". Not used: ht sd lower/upper, wt_sd, head circumference, sample sizes.
 * Rows for completed months 0 through ${MAX_MONTH} (18.0 years) are kept; the CSV also lists months 217-239.
 * This is a mean/SD reference. It is not an LMS table and no LMS values are derived from it.
 *
 * Row layout: [month, htMean (cm), htSd (cm), wtMean (kg), wtSdLower (kg), wtSdUpper (kg)].
 */
export type AchondroplasiaClarityRow = readonly [
  month: number,
  htMean: number,
  htSd: number,
  wtMean: number,
  wtSdLower: number,
  wtSdUpper: number,
];

export const ACHONDROPLASIA_CLARITY_SOURCE = {
  url: '${SOURCE_URL}',
  retrievedOn: '${retrievalDate}',
  sha256: '${sha256}',
} as const;

/** Completed months 0 through ${MAX_MONTH}, boys (CSV sex code 0). */
export const ACHONDROPLASIA_CLARITY_BOYS: ReadonlyArray<AchondroplasiaClarityRow> = [
${lines['0'].join('\n')}
];

/** Completed months 0 through ${MAX_MONTH}, girls (CSV sex code 1). */
export const ACHONDROPLASIA_CLARITY_GIRLS: ReadonlyArray<AchondroplasiaClarityRow> = [
${lines['1'].join('\n')}
];
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT.pathname} (sha256 ${sha256}); rows per sex: ${lines['0'].length}, ${lines['1'].length}`);
